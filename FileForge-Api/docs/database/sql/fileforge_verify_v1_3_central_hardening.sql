SELECT tablename, indexname FROM pg_indexes
WHERE indexname IN ('ix_central_files_recovery_due','ix_central_files_review','ix_central_upload_slots_user_recent','ix_central_upload_slots_open','ix_central_upload_slots_created','ix_sessions_expires','ix_sessions_user') ORDER BY 1, 2;

