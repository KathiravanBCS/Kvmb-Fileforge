-- 1. New objects. Expect 2 rows: core.sessions and storage.central_upload_slots.
SELECT table_schema, table_name FROM information_schema.tables
WHERE (table_schema, table_name) IN (('core','sessions'), ('storage','central_upload_slots')) ORDER BY 1, 2;

-- 2. New columns on storage.central_files. Expect 10 rows (recovery_attempts default 0, needs_review default false; the rest nullable).
SELECT column_name, data_type, is_nullable, column_default FROM information_schema.columns
WHERE table_schema = 'storage' AND table_name = 'central_files'
  AND column_name IN ('recovery_attempts','next_recovery_at','last_recovery_at','last_recovery_outcome','needs_review','review_reason','pending_size_bytes','pending_checksum_sha256','recovery_lease_token','recovery_lease_until')
ORDER BY column_name;

-- 2b. The upload slot lease token is mandatory and generated by the database. Expect 1 row: lease_token, uuid, NO, gen_random_uuid().
SELECT column_name, data_type, is_nullable, column_default FROM information_schema.columns
WHERE table_schema = 'storage' AND table_name = 'central_upload_slots' AND column_name = 'lease_token';

-- 3. Existing data untouched. Expect the same row count as before (1 at the time of writing), all recovery_attempts = 0, none flagged.
SELECT count(*) AS files, count(*) FILTER (WHERE recovery_attempts <> 0) AS touched_attempts, count(*) FILTER (WHERE needs_review) AS flagged,
       count(*) FILTER (WHERE next_recovery_at IS NOT NULL) AS scheduled, count(*) FILTER (WHERE recovery_lease_token IS NOT NULL) AS leased
FROM storage.central_files;

-- 4. Constraints and indexes of the new objects.
