BEGIN;

-- FILEFORGE AI v1.1: Microsoft identity and delegated OneDrive integration.
-- The following additions do not store Microsoft access or refresh tokens.
CREATE TABLE core.user_identities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES core.users(id),
 provider VARCHAR(40) NOT NULL CHECK(provider IN ('microsoft','local','other')),
 account_type VARCHAR(30) NOT NULL DEFAULT 'unknown' CHECK(account_type IN ('personal','organizational','unknown')),
 issuer TEXT NOT NULL, subject TEXT NOT NULL,
 tenant_id VARCHAR(100), home_account_id VARCHAR(255),
 provider_user_id VARCHAR(255), login_hint VARCHAR(320),
 is_primary BOOLEAN NOT NULL DEFAULT false,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_by BIGINT,
 updated_at TIMESTAMPTZ, updated_by BIGINT,
 is_deleted BOOLEAN NOT NULL DEFAULT false,
 deleted_at TIMESTAMPTZ, deleted_by BIGINT,
 CONSTRAINT user_identities_delete_consistency CHECK ((NOT is_deleted AND deleted_at IS NULL AND deleted_by IS NULL) OR (is_deleted AND deleted_at IS NOT NULL)),
 CONSTRAINT uq_user_identity_issuer_subject UNIQUE(provider,issuer,subject)
);
CREATE INDEX ix_user_identities_user ON core.user_identities(user_id) WHERE NOT is_deleted;
CREATE UNIQUE INDEX uq_user_primary_identity ON core.user_identities(user_id) WHERE is_primary AND NOT is_deleted;

-- Personal OneDrive is a delegated connection belonging to a user, not an app-only SharePoint site.
ALTER TABLE storage.connections
 ADD COLUMN owner_user_id BIGINT REFERENCES core.users(id),
 ADD COLUMN auth_mode VARCHAR(30) NOT NULL DEFAULT 'provider_specific'
   CHECK(auth_mode IN ('provider_specific','delegated','application','managed_identity')),
 ADD COLUMN connection_status VARCHAR(30) NOT NULL DEFAULT 'unverified'
   CHECK(connection_status IN ('unverified','connected','reauth_required','revoked','error')),
 ADD COLUMN external_drive_id TEXT,
 ADD COLUMN root_folder_item_id TEXT,
 ADD COLUMN root_folder_path TEXT,
 ADD COLUMN consented_scopes TEXT[],
 ADD COLUMN last_auth_at TIMESTAMPTZ;
CREATE INDEX ix_storage_connections_owner ON storage.connections(owner_user_id) WHERE NOT is_deleted;
COMMENT ON COLUMN storage.connections.secret_reference IS 'Reference to an external encrypted credential/token cache, never plaintext tokens.';
COMMENT ON COLUMN storage.connections.config IS 'Nonsecret configuration only; do not store Graph tokens, passwords, or refresh tokens.';
COMMENT ON COLUMN storage.connections.auth_mode IS 'OneDrive Personal requires delegated Microsoft Graph access; application mode is not suitable for consumer OneDrive.';

CREATE TABLE storage.folder_mappings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workspace_id BIGINT NOT NULL REFERENCES core.workspaces(id),
 connection_id BIGINT NOT NULL,
 module_code VARCHAR(80) NOT NULL,
 folder_name VARCHAR(255) NOT NULL,
 external_folder_item_id TEXT,
 relative_path TEXT NOT NULL,
 is_active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_by BIGINT,
 updated_at TIMESTAMPTZ, updated_by BIGINT,
 is_deleted BOOLEAN NOT NULL DEFAULT false,
 deleted_at TIMESTAMPTZ, deleted_by BIGINT,
 CONSTRAINT folder_mappings_delete_consistency CHECK ((NOT is_deleted AND deleted_at IS NULL AND deleted_by IS NULL) OR (is_deleted AND deleted_at IS NOT NULL)),
 CONSTRAINT fk_folder_mapping_connection_workspace FOREIGN KEY(connection_id,workspace_id) REFERENCES storage.connections(id,workspace_id)
);
CREATE UNIQUE INDEX uq_folder_mapping_active ON storage.folder_mappings(connection_id,module_code) WHERE NOT is_deleted;
CREATE INDEX ix_folder_mapping_workspace ON storage.folder_mappings(workspace_id) WHERE NOT is_deleted;

ALTER TABLE storage.files
 ADD COLUMN external_drive_id TEXT,
 ADD COLUMN external_web_url TEXT,
 ADD COLUMN external_etag TEXT,
 ADD COLUMN external_ctag TEXT,
 ADD COLUMN external_last_modified_at TIMESTAMPTZ;
COMMENT ON COLUMN storage.files.external_object_id IS 'Provider item identifier, e.g. Microsoft Graph driveItem.id; not a file byte payload.';

ALTER TABLE email.accounts
 ADD COLUMN owner_user_id BIGINT REFERENCES core.users(id),
 ADD COLUMN auth_mode VARCHAR(30) NOT NULL DEFAULT 'provider_specific'
   CHECK(auth_mode IN ('provider_specific','delegated','application')),
 ADD COLUMN connection_status VARCHAR(30) NOT NULL DEFAULT 'unverified'
   CHECK(connection_status IN ('unverified','connected','reauth_required','revoked','error'));
CREATE INDEX ix_email_accounts_owner ON email.accounts(owner_user_id) WHERE NOT is_deleted;
COMMENT ON COLUMN email.accounts.secret_reference IS 'External encrypted delegated token-cache reference, not a token.';

CREATE TRIGGER trg_user_identities_updated_at BEFORE UPDATE ON core.user_identities FOR EACH ROW EXECUTE FUNCTION core.set_updated_at();
CREATE TRIGGER trg_folder_mappings_updated_at BEFORE UPDATE ON storage.folder_mappings FOR EACH ROW EXECUTE FUNCTION core.set_updated_at();

