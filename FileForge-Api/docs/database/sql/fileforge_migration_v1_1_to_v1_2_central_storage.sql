-- FILEFORGE AI v1.2 ADDITIVE MIGRATION: Central Storage (administrator-owned OneDrive for all users).
-- Apply ONLY after fileforge_full_schema_v1_1.sql + fileforge_migration_v1_to_v1_1.sql (the live fileforge_db state).
-- NOT idempotent: a second run stops in the pre-flight check. Review, back up, then run in pgAdmin (Query Tool, F5).
-- The whole script is ONE transaction: if anything fails, nothing is applied.
--
-- What this adds (nothing existing is altered: storage.files and storage.connections are NOT touched):
--   core.system_admins        who is a global (system) administrator. Never written by the API.
--   storage.central_connection the ONE designated central OneDrive connection (encrypted MSAL token cache).
--   storage.central_files     metadata of files in the central OneDrive: owner, uploader, OneDrive ids, lifecycle.
--   master.entity_types       2 new rows (central_file, central_storage_connection) so audit.events can reference them.
--
-- Execution order (see also fileforge_seed_v1_2_grant_system_admin.sql):
--   1. this file                                       4. fileforge_verify_v1_2_central_storage.sql (read-only)
--   2. fileforge_seed_v1_2_grant_system_admin.sql      (rollback if ever needed: fileforge_rollback_v1_2_central_storage.sql)
--   3. tell Claude it ran; Claude then runs prisma validate/generate and builds the backend.

BEGIN;

-- ---------------------------------------------------------------------------------------------------------------
-- Pre-flight: fail with a clear message instead of a half-understood error.
-- ---------------------------------------------------------------------------------------------------------------
DO $$
BEGIN
  IF to_regclass('core.users') IS NULL OR to_regclass('core.user_identities') IS NULL THEN
    RAISE EXCEPTION 'Pre-flight: v1.1 core tables are missing (core.users / core.user_identities). Wrong database?';
  END IF;
  IF to_regclass('storage.connections') IS NULL OR to_regclass('storage.files') IS NULL THEN
    RAISE EXCEPTION 'Pre-flight: storage.connections / storage.files are missing. Wrong database?';
  END IF;
  IF to_regclass('audit.events') IS NULL OR to_regclass('master.entity_types') IS NULL THEN
    RAISE EXCEPTION 'Pre-flight: audit.events / master.entity_types are missing. Wrong database?';
  END IF;
  IF to_regprocedure('core.set_updated_at()') IS NULL THEN
    RAISE EXCEPTION 'Pre-flight: function core.set_updated_at() is missing.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM master.storage_provider_types WHERE code = 'onedrive' AND is_deleted = false) THEN
    RAISE EXCEPTION 'Pre-flight: master.storage_provider_types has no active "onedrive" row.';
  END IF;
  IF to_regclass('core.system_admins') IS NOT NULL
     OR to_regclass('storage.central_connection') IS NOT NULL
     OR to_regclass('storage.central_files') IS NOT NULL THEN
    RAISE EXCEPTION 'Pre-flight: a central storage table already exists. This migration was already applied (or partly applied by hand).';
  END IF;
END $$;


-- ---------------------------------------------------------------------------------------------------------------
-- 1. core.system_admins: global administrators.
--    There is NO API that writes this table. Rows are created only by reviewed SQL (see the seed file).
--    Application code must treat it as read-only. Workspace roles (owner/admin/...) are NOT system administrators.
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE core.system_admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES core.users(id),
  is_active BOOLEAN NOT NULL DEFAULT true,
  granted_by BIGINT REFERENCES core.users(id),
  granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  note VARCHAR(300),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by BIGINT,
  updated_at TIMESTAMPTZ,
  updated_by BIGINT,
  is_deleted BOOLEAN NOT NULL DEFAULT false,
  deleted_at TIMESTAMPTZ,
  deleted_by BIGINT,
  CONSTRAINT system_admins_delete_consistency CHECK ((is_deleted = false AND deleted_at IS NULL AND deleted_by IS NULL) OR (is_deleted = true AND deleted_at IS NOT NULL))
);

CREATE INDEX ix_system_admins_active ON core.system_admins(id) WHERE is_deleted = false;
-- One live row per user. Revoke by is_active = false (or soft delete); re-grant by updating that row.
CREATE UNIQUE INDEX uq_system_admins_user ON core.system_admins(user_id) WHERE is_deleted = false;

COMMENT ON TABLE core.system_admins IS 'Global system administrators. Read-only for the application: rows are created only by reviewed SQL. Access requires is_active AND NOT is_deleted AND an active core.users row.';


-- ---------------------------------------------------------------------------------------------------------------
-- 2. master.entity_types: codes used by audit.events for central storage.
--    (Inserts new rows only; existing rows are untouched.)
-- ---------------------------------------------------------------------------------------------------------------
INSERT INTO master.entity_types(code, name, description) VALUES
  ('central_file', 'Central storage file', 'A file stored in the centralized administrator-owned OneDrive'),
  ('central_storage_connection', 'Central storage connection', 'The designated central OneDrive connection')
ON CONFLICT (code) DO NOTHING;


-- ---------------------------------------------------------------------------------------------------------------
-- 3. storage.central_connection: the single designated central OneDrive connection.
--    The MSAL token cache (which holds the refresh token) is stored ONLY as AES-256-GCM ciphertext.
--    Plaintext tokens never reach this table. The key comes from CENTRAL_STORAGE_ENCRYPTION_KEY (not in the database).
--    GCM additional authenticated data (AAD) is built by the application from: key version + row id + account_subject.
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE storage.central_connection (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_type_id BIGINT NOT NULL REFERENCES master.storage_provider_types(id),
  -- The FileForge user whose Microsoft account is the central storage account (approved: core.users.id = 1).
  owner_user_id BIGINT NOT NULL REFERENCES core.users(id),

  -- Designated Microsoft identity. Matched by issuer + subject (oid), NEVER by e-mail. Immutable once saved (trigger below).
  account_issuer TEXT NOT NULL,
  account_subject TEXT NOT NULL,
  account_tenant_id VARCHAR(100),
  account_type VARCHAR(30) NOT NULL DEFAULT 'unknown' CHECK (account_type IN ('personal','organizational','unknown')),
  home_account_id VARCHAR(255) NOT NULL,
  account_email VARCHAR(320),
  account_display_name VARCHAR(200),

  -- Drive and layout: FileForge-Central/ (root) and FileForge-Central/users/ (parent of the per-user folders).
  external_drive_id TEXT NOT NULL,
  root_folder_item_id TEXT NOT NULL,
  root_folder_path TEXT NOT NULL DEFAULT 'FileForge-Central',
  users_folder_item_id TEXT NOT NULL,

  connection_status VARCHAR(30) NOT NULL DEFAULT 'unverified' CHECK (connection_status IN ('unverified','connected','reauth_required','revoked','error')),
  consented_scopes TEXT[] NOT NULL DEFAULT '{}',

  -- Encrypted MSAL cache (AES-256-GCM). nonce = 12 random bytes per write, auth_tag = 16 bytes.
  token_cache_ciphertext BYTEA NOT NULL,
  token_cache_nonce BYTEA NOT NULL,
  token_cache_auth_tag BYTEA NOT NULL,
  encryption_key_version SMALLINT NOT NULL DEFAULT 1,
  -- Compare-and-swap counter: every cache write is "UPDATE ... WHERE cache_revision = <value read>", so a stale
  -- writer (second process, concurrent refresh) can never overwrite a newer cache.
  cache_revision BIGINT NOT NULL DEFAULT 1,
  cache_updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  last_auth_at TIMESTAMPTZ,
  last_verified_at TIMESTAMPTZ,
  last_error_code VARCHAR(60),
  last_error_at TIMESTAMPTZ,

  -- Last quota reading from Graph (/drive.quota); informational only.
  quota_total_bytes BIGINT CHECK (quota_total_bytes >= 0),
  quota_used_bytes BIGINT CHECK (quota_used_bytes >= 0),
  quota_remaining_bytes BIGINT CHECK (quota_remaining_bytes >= 0),
  quota_state VARCHAR(20),
  quota_checked_at TIMESTAMPTZ,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by BIGINT,
  updated_at TIMESTAMPTZ,
  updated_by BIGINT,
  is_deleted BOOLEAN NOT NULL DEFAULT false,
  deleted_at TIMESTAMPTZ,
  deleted_by BIGINT,

  CONSTRAINT central_connection_delete_consistency CHECK ((is_deleted = false AND deleted_at IS NULL AND deleted_by IS NULL) OR (is_deleted = true AND deleted_at IS NOT NULL)),
  CONSTRAINT central_connection_nonce_length CHECK (octet_length(token_cache_nonce) = 12),
  CONSTRAINT central_connection_tag_length CHECK (octet_length(token_cache_auth_tag) = 16),
  CONSTRAINT central_connection_cache_not_empty CHECK (octet_length(token_cache_ciphertext) > 0),
  CONSTRAINT central_connection_key_version CHECK (encryption_key_version > 0),
  CONSTRAINT central_connection_revision CHECK (cache_revision > 0),
  -- The central root can never be the personal File Manager root.
  CONSTRAINT central_connection_root_not_personal CHECK (lower(root_folder_path) <> 'fileforge')
);

CREATE INDEX ix_central_connection_active ON storage.central_connection(id) WHERE is_deleted = false;
-- Exactly one live (not soft-deleted) central connection.
CREATE UNIQUE INDEX uq_central_connection_single ON storage.central_connection ((true)) WHERE is_deleted = false;

-- Identity guard. INSERT: the account must be a Microsoft identity that belongs to owner_user_id (core.user_identities).
-- UPDATE: owner, issuer, subject and drive can never change on a row, so a different Microsoft account cannot silently
-- take over the connection. Deliberate replacement = soft-delete this row, then insert a new one (done by hand, reviewed).
CREATE OR REPLACE FUNCTION storage.guard_central_connection_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NOT EXISTS (
      SELECT 1 FROM core.user_identities ui
      WHERE ui.user_id = NEW.owner_user_id
        AND ui.provider = 'microsoft'
        AND ui.issuer = NEW.account_issuer
        AND ui.subject = NEW.account_subject
        AND ui.is_deleted = false
    ) THEN
      RAISE EXCEPTION 'central_connection: the Microsoft account is not an identity of owner_user_id %', NEW.owner_user_id
        USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;

  IF NEW.owner_user_id IS DISTINCT FROM OLD.owner_user_id
     OR NEW.account_issuer IS DISTINCT FROM OLD.account_issuer
     OR NEW.account_subject IS DISTINCT FROM OLD.account_subject
     OR NEW.external_drive_id IS DISTINCT FROM OLD.external_drive_id THEN
    RAISE EXCEPTION 'central_connection: the designated Microsoft account and drive cannot be changed on an existing connection'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END; $$;

CREATE TRIGGER trg_central_connection_identity BEFORE INSERT OR UPDATE ON storage.central_connection FOR EACH ROW EXECUTE FUNCTION storage.guard_central_connection_identity();

COMMENT ON TABLE storage.central_connection IS 'The single designated central OneDrive connection (delegated Files.ReadWrite). Holds the MSAL cache only as AES-256-GCM ciphertext.';
COMMENT ON COLUMN storage.central_connection.token_cache_ciphertext IS 'AES-256-GCM ciphertext of the serialized MSAL cache. Never plaintext. Key: env CENTRAL_STORAGE_ENCRYPTION_KEY (versioned by encryption_key_version).';
COMMENT ON COLUMN storage.central_connection.cache_revision IS 'Optimistic-concurrency counter for cache writes (compare-and-swap).';
COMMENT ON COLUMN storage.central_connection.account_subject IS 'Microsoft oid claim. Identity is matched on issuer + subject, never on e-mail.';


-- ---------------------------------------------------------------------------------------------------------------
-- 4. storage.central_files: metadata of files held in the central OneDrive.
--    owner_user_id decides who may see the file; uploaded_by records who performed the upload (owner or an administrator).
--    File CONTENT lives only in OneDrive. The OneDrive item is named by stored_name (generated uuid + extension),
--    so a user-facing rename only changes display_name here.
--    Lifecycle: pending -> uploading -> ready;  ready -> replacing -> ready;  ready -> deleting -> deleted;  failed.
--    A file is readable while ready or replacing. deleting/deleted rows are soft-deleted (is_deleted = true).
-- ---------------------------------------------------------------------------------------------------------------
CREATE TABLE storage.central_files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  connection_id BIGINT NOT NULL REFERENCES storage.central_connection(id),
  owner_user_id BIGINT NOT NULL REFERENCES core.users(id),
  uploaded_by BIGINT NOT NULL REFERENCES core.users(id),

  display_name TEXT NOT NULL,
  stored_name VARCHAR(100) NOT NULL,
  file_extension VARCHAR(16),
  mime_type VARCHAR(255) NOT NULL,
  size_bytes BIGINT NOT NULL DEFAULT 0,
  checksum_sha256 VARCHAR(64),
  content_version INTEGER NOT NULL DEFAULT 1,

  external_drive_id TEXT NOT NULL,
  external_item_id TEXT,
  external_etag TEXT,
  external_ctag TEXT,
  external_created_at TIMESTAMPTZ,
  external_last_modified_at TIMESTAMPTZ,

  upload_status VARCHAR(30) NOT NULL DEFAULT 'pending',
  uploaded_at TIMESTAMPTZ,
  last_error_code VARCHAR(60),

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by BIGINT,
  updated_at TIMESTAMPTZ,
  updated_by BIGINT,
  is_deleted BOOLEAN NOT NULL DEFAULT false,
  deleted_at TIMESTAMPTZ,
  deleted_by BIGINT,

  CONSTRAINT central_files_delete_consistency CHECK ((is_deleted = false AND deleted_at IS NULL AND deleted_by IS NULL) OR (is_deleted = true AND deleted_at IS NOT NULL)),
  CONSTRAINT central_files_status_check CHECK (upload_status IN ('pending','uploading','ready','replacing','failed','deleting','deleted')),
  CONSTRAINT central_files_size_check CHECK (size_bytes >= 0),
  CONSTRAINT central_files_version_check CHECK (content_version > 0),
  CONSTRAINT central_files_display_name_length CHECK (char_length(display_name) BETWEEN 1 AND 255),
  -- Generated names only: "<uuid>" or "<uuid>.<ext>". No separators, no traversal, nothing user-chosen.
  CONSTRAINT central_files_stored_name_format CHECK (stored_name ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}(\.[a-z0-9]{1,16})?$'),
  CONSTRAINT central_files_extension_format CHECK (file_extension IS NULL OR file_extension ~ '^[a-z0-9]{1,16}$'),
  -- A readable file always points at its OneDrive item and has finished uploading.
  CONSTRAINT central_files_ready_has_item CHECK (upload_status NOT IN ('ready','replacing') OR (external_item_id IS NOT NULL AND uploaded_at IS NOT NULL)),
  -- deleting / deleted are soft-deleted states, so lists (which filter is_deleted = false) never show them.
  CONSTRAINT central_files_deleted_states CHECK (upload_status NOT IN ('deleting','deleted') OR is_deleted = true)
);

CREATE INDEX ix_central_files_active ON storage.central_files(id) WHERE is_deleted = false;
-- "My files" (newest first) and per-user usage.
CREATE INDEX ix_central_files_owner ON storage.central_files(owner_user_id, created_at DESC) WHERE is_deleted = false;
-- Administrator list across all users (newest first).
CREATE INDEX ix_central_files_created ON storage.central_files(created_at DESC) WHERE is_deleted = false;
-- One live row per OneDrive item.
CREATE UNIQUE INDEX uq_central_file_item ON storage.central_files(external_drive_id, external_item_id) WHERE external_item_id IS NOT NULL AND is_deleted = false;
-- Generated names never repeat within an owner's folder (rows of every status count: a recycled name must not be reused).
CREATE UNIQUE INDEX uq_central_file_stored_name ON storage.central_files(owner_user_id, stored_name);
-- Rows that need attention (interrupted uploads/replacements/deletes) for recovery and cleanup.
CREATE INDEX ix_central_files_needs_attention ON storage.central_files(upload_status, updated_at) WHERE upload_status IN ('pending','uploading','replacing','deleting','failed');

COMMENT ON TABLE storage.central_files IS 'Metadata of files in the central administrator-owned OneDrive. owner_user_id is the only basis for user access; content lives in OneDrive.';
COMMENT ON COLUMN storage.central_files.stored_name IS 'Generated OneDrive item name (uuid[.ext]). Immutable; display_name is what users rename.';
COMMENT ON COLUMN storage.central_files.uploaded_by IS 'Who performed the upload: the owner, or a system administrator uploading on the owner''s behalf.';


-- ---------------------------------------------------------------------------------------------------------------
-- 5. updated_at triggers (same convention as every other table).
-- ---------------------------------------------------------------------------------------------------------------
CREATE TRIGGER trg_system_admins_updated_at BEFORE UPDATE ON core.system_admins FOR EACH ROW EXECUTE FUNCTION core.set_updated_at();
CREATE TRIGGER trg_central_connection_updated_at BEFORE UPDATE ON storage.central_connection FOR EACH ROW EXECUTE FUNCTION core.set_updated_at();
CREATE TRIGGER trg_central_files_updated_at BEFORE UPDATE ON storage.central_files FOR EACH ROW EXECUTE FUNCTION core.set_updated_at();

COMMIT;
